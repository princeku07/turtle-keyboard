// Composed text styles — each spec ({font-family, font-weight, font-size,
// line-height, letter-spacing}) renders as a card showing the live style
// applied to a sample sentence.
function renderTextStyleSection(section) {
  const cards = section.leaves.map(leaf => {
    const s = leaf.spec;
    const family = s["font-family"] || "system";
    const size   = Number(s["font-size"]) || 16;
    const weight = mapWeight(s["font-weight"]);
    const line   = s["line-height"] !== undefined ? Number(s["line-height"]) : null;
    const track  = s["letter-spacing"] !== undefined ? Number(s["letter-spacing"]) : null;
    const stack  = cssFontStack(family);
    const styleAttr = [
      `font-family: ${stack}`,
      `font-size: ${size}px`,
      `font-weight: ${weight}`,
      line !== null ? `line-height: ${line > 4 ? line + "px" : line}` : null,
      track !== null ? `letter-spacing: ${track}px` : null,
    ].filter(Boolean).join("; ");

    const specRows = Object.entries(s)
      .filter(([k]) => !k.startsWith("_"))
      .map(([k, v]) => `<dt>${escapeHtml(k)}</dt><dd>${escapeHtml(String(v))}</dd>`)
      .join("");

    const scopes = formatScopes(leaf.scopes);
    return `
        <article class="ts-card">
          <div class="ts-sample" style="${styleAttr}">${escapeHtml(leaf.name)}</div>
          <div class="ts-meta">
            <code class="slug">${leaf.slug}</code>
            <dl class="ts-spec">${specRows}</dl>
            <dl class="ts-extra">
              <dt>Figma&nbsp;ID</dt><dd>${leaf.figmaId ? escapeHtml(leaf.figmaId) : "—"}</dd>
              <dt>Scopes</dt><dd>${scopes}</dd>
            </dl>
          </div>
        </article>`;
  }).join("");
  return `
  <section>
    <div class="section-head">
      <h2>${escapeHtml(section.name)} <span class="tier">Foundation · Text styles</span></h2>
      <span class="badge">${section.leaves.length} styles</span>
    </div>
    <div class="ts-grid">${cards}
    </div>
  </section>`;
}

