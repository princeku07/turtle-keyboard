function renderTypographySection(section) {
  // Group leaves by font-family value so the preview shows one block per
  // family with all its named variants underneath.
  const byFamily = new Map();
  for (const leaf of section.leaves) {
    const family = leaf.value;
    if (!byFamily.has(family)) byFamily.set(family, []);
    byFamily.get(family).push(leaf);
  }

  const blocks = Array.from(byFamily.entries()).map(([family, leaves]) => {
    const sample = `The quick brown fox jumps over the lazy dog`;
    const rows = leaves.map(leaf => {
      const p = leaf.platforms;
      const scopes = formatScopes(leaf.scopes);
      return `
        <tr>
          <td>${escapeHtml(leaf.name)}</td>
          <td>${leaf.slug}</td>
          <td class="muted">${leaf.figmaId ? escapeHtml(leaf.figmaId) : "—"}</td>
          <td class="muted">${scopes}</td>
          <td class="muted">${escapeHtml(p.css)}</td>
        </tr>`;
    }).join("");
    return `
    <div class="type-block">
      <div class="type-sample" style="font-family: ${cssFontStack(family)};">${sample}</div>
      <div class="type-meta">
        <code class="family">${escapeHtml(family)}</code>
        <span class="count">${leaves.length} variants</span>
      </div>
      <table class="scale-table">
        <thead><tr><th>Variant</th><th>Slug</th><th>Figma ID</th><th>Scopes</th><th>CSS</th></tr></thead>
        <tbody>${rows}
        </tbody>
      </table>
    </div>`;
  }).join("\n");

  return `
  <section>
    <div class="section-head">
      <h2>${escapeHtml(section.name)} <span class="tier">Foundation · Strings</span></h2>
      <span class="badge">${byFamily.size} ${byFamily.size === 1 ? "family" : "families"} · ${section.leaves.length} tokens</span>
    </div>
    <div class="type-grid">${blocks}
    </div>
  </section>`;
}

function cssFontStack(family) {
  const safe = String(family).replace(/['"]/g, "");
  return `'${safe}', system-ui, -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif`;
}

