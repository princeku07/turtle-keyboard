const repoRoot = join(__dirname, "..");

const KNOWN_TYPES = new Set(["color", "dimension", "fontFamily", "fontWeight", "duration", "cubicBezier", "shadow", "typography", "string", "number"]);
const HEX = /^#([0-9a-fA-F]{6}|[0-9a-fA-F]{8})$/;
const DIM = /^-?(\d+(?:\.\d+)?)(px|pt|rem|em)?$/;
const HEADER = "// AUTO-GENERATED by design-system/build.mjs. Edit token.json, not this file.";
const XML_HEADER = "<!-- AUTO-GENERATED by design-system/build.mjs. Edit token.json, not this file. -->";

