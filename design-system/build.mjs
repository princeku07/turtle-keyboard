function collectSections(rawTokens) {
  const sections = [];
  const rootStrings = [];

  for (const [groupName, groupValue] of Object.entries(rawTokens)) {
    if (groupName.startsWith("$")) continue;
    if (!groupValue || typeof groupValue !== "object") continue;

    // Root-level string leaf (legacy flat-fonts export) — collect into a
    // synthetic Typography section at the end.
    if ("$value" in groupValue && groupValue.$type === "string") {
      const ext = groupValue.$extensions || {};
      rootStrings.push({
        name: groupName,
        slug: slugify(groupName),
        value: groupValue.$value,
        figmaId: ext["com.figma.variableId"] || null,
        scopes: ext["com.figma.scopes"] || null,
      });
      continue;
    }
    if ("$value" in groupValue) continue;

    const buckets = { colors: [], numbers: [], strings: [], textStyles: [] };
    walkGroup(groupValue, [groupName], buckets);

    // Order: text-styles first (richest), then colors, then numbers, then
    // any leftover plain strings. Each top-level group can fan out into
    // multiple kinds if it mixes content.
    if (buckets.textStyles.length > 0) {
      sections.push({ name: groupName, leaves: buckets.textStyles, kind: "text-style" });
    }
    if (buckets.colors.length > 0) {
      const isScale = buckets.colors.every(l => /^\d+$/.test(String(l.name).trim()));
      if (isScale) buckets.colors.sort((a, b) => Number(a.name) - Number(b.name));
      sections.push({ name: groupName, leaves: buckets.colors, isScale, kind: "color" });
    }
    if (buckets.numbers.length > 0) {
      buckets.numbers.sort((a, b) => a.value - b.value);
      sections.push({ name: groupName, leaves: buckets.numbers, kind: "number" });
    }
    if (buckets.strings.length > 0 && buckets.textStyles.length === 0) {
      // Strings stand alone only when no text-styles consumed them.
      sections.push({ name: groupName, leaves: buckets.strings, kind: "string-list" });
    }
  }

  if (rootStrings.length > 0) {
    sections.push({ name: "Typography", leaves: rootStrings, kind: "typography" });
  }
  return sections;
}

function walkGroup(group, path, buckets) {
  // A text-style spec is a group whose direct children are all $value-bearing
  // leaves and include font-family or font-size. Capture it and stop descending.
  const spec = extractTextStyle(group);
  if (spec) {
    buckets.textStyles.push({
      name: path[path.length - 1] || "Style",
      slug: path.map(slugify).join("."),
      spec,
      figmaId: spec._figmaId,
      scopes: spec._scopes,
    });
    return;
  }

  for (const [k, v] of Object.entries(group)) {
    if (k.startsWith("$")) continue;
    if (!v || typeof v !== "object") continue;
    if ("$value" in v && "$type" in v) {
      const slug = [...path, k].map(slugify).join(".");
      const ext = v.$extensions || {};
      const common = {
        name: k,
        slug,
        figmaId: ext["com.figma.variableId"] || null,
        scopes: ext["com.figma.scopes"] || null,
      };
      if (v.$type === "color") {
        const hex = extractHex(v);
        if (hex) buckets.colors.push({ ...common, hex });
      } else if (v.$type === "number") {
        buckets.numbers.push({ ...common, value: v.$value });
      } else if (v.$type === "string") {
        buckets.strings.push({ ...common, value: v.$value });
      }
    } else {
      walkGroup(v, [...path, k], buckets);
    }
  }
}

function extractTextStyle(group) {
  const keys = Object.keys(group).filter(k => !k.startsWith("$"));
  if (keys.length === 0) return null;
  let hasFontFamily = false, hasFontSize = false;
  const spec = {};
  let firstExt = null;
  for (const k of keys) {
    const v = group[k];
    if (!v || typeof v !== "object") return null;
    if (!("$value" in v) || !("$type" in v)) return null;
    spec[k] = v.$value;
    if (!firstExt) firstExt = v.$extensions || {};
    const lower = k.toLowerCase();
    if (lower === "font-family") hasFontFamily = true;
    if (lower === "font-size")   hasFontSize = true;
  }
  if (!hasFontFamily && !hasFontSize) return null;
  spec._ext = firstExt;
  spec._figmaId = firstExt["com.figma.variableId"] || null;
  spec._scopes = firstExt["com.figma.scopes"] || null;
  return spec;
}

function extractHex(node) {
  const v = node.$value;
  if (typeof v === "string" && /^#[0-9a-fA-F]{6,8}$/.test(v)) return v.toUpperCase();
  if (v && typeof v === "object" && typeof v.hex === "string") return v.hex.toUpperCase();
  return null;
}

