// Single-source design-system generator. Reads token.json (regenerated from
// the Value.tokens*.json Figma exports via merge-figma.mjs) and emits
// platform-native files committed alongside this script — no build-time
// coupling, each platform consumes its native artifact as-is.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

