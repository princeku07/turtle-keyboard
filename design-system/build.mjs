// Figma exports font-weight as words ("Bold", "Medium"); map to numeric so
// CSS picks up an accurate weight even when the named family doesn't load.
function mapWeight(w) {
  if (typeof w === "number") return w;
  const norm = String(w || "").toLowerCase().replace(/[\s-]/g, "");
  if (norm.includes("thin")) return 100;
  if (norm.includes("extralight") || norm.includes("ultralight")) return 200;
  if (norm.includes("light")) return 300;
  if (norm.includes("regular") || norm === "normal" || norm === "") return 400;
  if (norm.includes("medium")) return 500;
  if (norm.includes("semibold") || norm.includes("demibold")) return 600;
  if (norm.includes("extrabold") || norm.includes("ultrabold")) return 800;
  if (norm.includes("black") || norm.includes("heavy")) return 900;
  if (norm.includes("bold")) return 700;
  return 400;
}

function formatScopes(scopes) {
  if (!Array.isArray(scopes) || scopes.length === 0) return "—";
  return scopes.map(escapeHtml).join(", ");
}

function isDarkHex(hex) {
  if (!hex || typeof hex !== "string") return true;
  const m = hex.replace("#", "");
  if (m.length < 6) return true;
  const r = parseInt(m.slice(0, 2), 16) / 255;
  const g = parseInt(m.slice(2, 4), 16) / 255;
  const b = parseInt(m.slice(4, 6), 16) / 255;
  const lin = c => c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
  const L = 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
  return L < 0.55;
}

function escapeHtml(s) {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

